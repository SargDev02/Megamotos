alter table public.liquidaciones
  alter column total_entregado set default 0,
  alter column total_entregado set not null,
  add constraint liquidaciones_descuento_prestamos_check
    check (descuento_prestamos >= 0),
  add constraint liquidaciones_total_entregado_check
    check (total_entregado >= 0),
  add constraint liquidaciones_descuento_no_supera_total_check
    check (descuento_prestamos <= total_pagado),
  add constraint liquidaciones_totales_consistentes_check
    check (
      total_entregado =
      greatest(total_pagado - descuento_prestamos, 0)
    );

create table public.prestamos_mecanicos (
  id bigint generated by default as identity primary key,
  mecanico_id uuid not null
    references public.perfiles(id) on delete restrict,
  descripcion text not null,
  monto_original numeric(14, 0) not null,
  created_by uuid not null
    references public.perfiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint prestamos_mecanicos_descripcion_check
    check (btrim(descripcion) <> ''),
  constraint prestamos_mecanicos_monto_original_check
    check (monto_original > 0)
);

create table public.liquidacion_prestamos (
  liquidacion_id bigint not null
    references public.liquidaciones(id) on delete restrict,
  prestamo_id bigint not null
    references public.prestamos_mecanicos(id) on delete restrict,
  monto_aplicado numeric(14, 0) not null,
  created_at timestamptz not null default now(),
  constraint liquidacion_prestamos_pkey
    primary key (liquidacion_id, prestamo_id),
  constraint liquidacion_prestamos_monto_aplicado_check
    check (monto_aplicado > 0)
);

create index prestamos_mecanicos_mecanico_fifo_idx
