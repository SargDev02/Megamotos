create or replace function public.registrar_prestamo_mecanico(
  p_mecanico_id uuid,
  p_descripcion text,
  p_monto numeric
)
returns table (
  prestamo_id bigint,
  mecanico_id uuid,
  descripcion text,
  monto_original numeric,
  created_by uuid,
  created_at timestamptz
)
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_descripcion text;
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if private.current_user_role() is distinct from 'ADMIN' then
    raise exception 'Solo ADMIN puede registrar prestamos';
  end if;

  perform p.id
  from public.perfiles as p
  where p.id = p_mecanico_id
    and p.rol = 'MECANICO'
  for update;

  if not found then
    raise exception 'El mecanico indicado no existe';
  end if;

  v_descripcion := btrim(p_descripcion);

  if v_descripcion is null or v_descripcion = '' then
    raise exception 'La descripcion es obligatoria';
  end if;

  if p_monto is null or p_monto <= 0 then
    raise exception 'El valor del prestamo debe ser mayor que cero';
  end if;

  return query
  insert into public.prestamos_mecanicos as pm (
    mecanico_id,
    descripcion,
    monto_original,
    created_by
  )
  values (
    p_mecanico_id,
    v_descripcion,
    p_monto,
    auth.uid()
  )
  returning
    pm.id,
    pm.mecanico_id,
    pm.descripcion,
    pm.monto_original,
    pm.created_by,
    pm.created_at;
end;
$function$;

create or replace function public.listar_prestamos_mecanicos()
returns table (
  prestamo_id bigint,
  mecanico_id uuid,
  mecanico_nombre text,
  descripcion text,
  monto_original numeric,
  monto_aplicado numeric,
  saldo_pendiente numeric,
  created_at timestamptz
)
language plpgsql
stable
security invoker
set search_path = ''
as $function$
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if private.current_user_role() is distinct from 'ADMIN' then
    raise exception 'Solo ADMIN puede consultar prestamos';
  end if;

  return query
  select
    pm.id,
    pm.mecanico_id,
    p.nombre,
    pm.descripcion,
    pm.monto_original,
    coalesce(ap.monto_aplicado, 0),
    pm.monto_original - coalesce(ap.monto_aplicado, 0),
    pm.created_at
  from public.prestamos_mecanicos as pm
  join public.perfiles as p
    on p.id = pm.mecanico_id
  left join lateral (
    select sum(lp.monto_aplicado) as monto_aplicado
    from public.liquidacion_prestamos as lp
    where lp.prestamo_id = pm.id
  ) as ap on true
  order by
    (pm.monto_original - coalesce(ap.monto_aplicado, 0) > 0) desc,
    pm.created_at,
    pm.id;
end;
$function$;

