create function public.listar_historial_pagos()
returns table (
  liquidacion_id bigint,
  fecha_pago date,
  created_at timestamptz,
  mecanico_id uuid,
  mecanico_nombre text,
  total_pagado numeric,
  descuento_prestamos numeric,
  total_entregado numeric,
  total_cobrado numeric,
  moto_placa text,
  moto_marca text,
  moto_modelo text,
  monto_pagado numeric,
  trabajos jsonb
)
language plpgsql
security invoker
set search_path = ''
as $function$
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if private.current_user_role() is distinct from 'ADMIN' then
    raise exception 'Solo ADMIN puede consultar el historial de pagos';
  end if;

  return query
  select
    l.id,
    l.fecha_pago,
    l.created_at,
    l.mecanico_id,
    p.nombre,
    l.total_pagado,
    l.descuento_prestamos,
    l.total_entregado,
    o.total,
    m.placa,
    mm.nombre,
    m.modelo,
    lo.monto_pagado,
    coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'id', t.id,
            'nombre_trabajo', t.nombre_trabajo
          )
          order by t.id
        )
        from public.trabajos_orden as t
        where t.orden_id = o.id
      ),
      '[]'::jsonb
    )
  from public.liquidaciones as l
  join public.perfiles as p
    on p.id = l.mecanico_id
  join public.liquidacion_ordenes as lo
    on lo.liquidacion_id = l.id
  join public.ordenes as o
    on o.id = lo.orden_id
  join public.motos as m
    on m.id = o.moto_id
  join public.marcas_moto as mm
    on mm.id = m.marca_id
  order by l.created_at desc, l.id desc, m.placa;
end;
$function$;

drop function public.liquidar_ordenes_mecanico(uuid, bigint[]);

create function public.liquidar_ordenes_mecanico(
  p_mecanico_id uuid,
  p_orden_ids bigint[]
)
returns table (
  liquidacion_id bigint,
  total_pagado numeric,
  descuento_prestamos numeric,
  total_entregado numeric,
  cantidad_ordenes integer,
  fecha_pago date
)
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_liquidacion_id bigint;
  v_orden_ids bigint[];
  v_cantidad_solicitada integer;
  v_cantidad_distinta integer;
  v_cantidad_valida integer;
  v_cantidad_insertada integer;
  v_total_bruto numeric(14, 0);
  v_descuento_prestamos numeric(14, 0) := 0;
  v_total_entregado numeric(14, 0);
  v_monto_restante numeric(14, 0);
  v_monto_aplicar numeric(14, 0);
  v_prestamo record;
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if private.current_user_role() is distinct from 'ADMIN' then
    raise exception 'Solo ADMIN puede registrar pagos';
  end if;

  perform p.id
  from public.perfiles as p
  where p.id = p_mecanico_id
    and p.rol = 'MECANICO'
  for update;

  if not found then
    raise exception 'El mecanico indicado no existe';
  end if;

  if coalesce(cardinality(p_orden_ids), 0) = 0 then
    raise exception 'Selecciona al menos una orden para liquidar';
  end if;

  if exists (
    select 1
    from unnest(p_orden_ids) as seleccion(orden_id)
    where seleccion.orden_id is null
  ) then
    raise exception 'La seleccion contiene ordenes invalidas';
  end if;

  select
    array_agg(distinct seleccion.orden_id order by seleccion.orden_id),
    count(*)::integer,
    count(distinct seleccion.orden_id)::integer
  into
    v_orden_ids,
    v_cantidad_solicitada,
    v_cantidad_distinta
  from unnest(p_orden_ids) as seleccion(orden_id);

  if v_cantidad_solicitada <> v_cantidad_distinta then
    raise exception 'La seleccion contiene ordenes duplicadas';
  end if;

  perform o.id
  from public.ordenes as o
  where o.id = any(v_orden_ids)
  order by o.id
  for update;

  select count(*)::integer
  into v_cantidad_valida
  from public.ordenes as o
  where o.id = any(v_orden_ids)
    and o.mecanico_id = p_mecanico_id
    and o.estado = 'TERMINADA'
    and not exists (
      select 1
      from public.liquidacion_ordenes as lo
      where lo.orden_id = o.id
    );

  if v_cantidad_valida <> v_cantidad_solicitada then
    raise exception
      'Una o mas ordenes no existen, no pertenecen al mecanico, no estan terminadas o ya fueron liquidadas';
  end if;

  select coalesce(sum(o.pago_mecanico), 0)::numeric(14, 0)
  into v_total_bruto
  from public.ordenes as o
  where o.id = any(v_orden_ids);

  insert into public.liquidaciones (
    mecanico_id,
    fecha_pago,
    total_pagado,
    descuento_prestamos,
    total_entregado,
    created_by
  )
  values (
    p_mecanico_id,
    current_date,
    v_total_bruto,
    0,
    v_total_bruto,
    auth.uid()
  )
  returning id into v_liquidacion_id;

  insert into public.liquidacion_ordenes (
    liquidacion_id,
    orden_id,
    monto_pagado
  )
  select
    v_liquidacion_id,
    o.id,
    o.pago_mecanico
  from public.ordenes as o
  where o.id = any(v_orden_ids)
  order by o.id;

  get diagnostics v_cantidad_insertada = row_count;

  if v_cantidad_insertada <> v_cantidad_solicitada then
    raise exception 'No fue posible registrar todas las ordenes seleccionadas';
  end if;

  perform pm.id
  from public.prestamos_mecanicos as pm
  where pm.mecanico_id = p_mecanico_id
  order by pm.created_at, pm.id
  for update;

  v_monto_restante := v_total_bruto;

  for v_prestamo in
    select
      pm.id,
      pm.monto_original - coalesce(sum(lp.monto_aplicado), 0) as saldo_pendiente
    from public.prestamos_mecanicos as pm
    left join public.liquidacion_prestamos as lp
      on lp.prestamo_id = pm.id
    where pm.mecanico_id = p_mecanico_id
    group by pm.id, pm.monto_original, pm.created_at
    having pm.monto_original - coalesce(sum(lp.monto_aplicado), 0) > 0
    order by pm.created_at, pm.id
  loop
    exit when v_monto_restante <= 0;

    v_monto_aplicar := least(
      v_prestamo.saldo_pendiente,
      v_monto_restante
    );

    insert into public.liquidacion_prestamos (
      liquidacion_id,
      prestamo_id,
      monto_aplicado
    )
    values (
      v_liquidacion_id,
      v_prestamo.id,
      v_monto_aplicar
    );

    v_descuento_prestamos :=
      v_descuento_prestamos + v_monto_aplicar;
    v_monto_restante :=
      v_monto_restante - v_monto_aplicar;
  end loop;

  v_total_entregado := greatest(
    v_total_bruto - v_descuento_prestamos,
    0
  );

  update public.liquidaciones as l
  set
    descuento_prestamos = v_descuento_prestamos,
    total_entregado = v_total_entregado,
    updated_at = now()
  where l.id = v_liquidacion_id;

  return query
  select
    l.id,
    l.total_pagado,
    l.descuento_prestamos,
    l.total_entregado,
    v_cantidad_insertada,
    l.fecha_pago
  from public.liquidaciones as l
  where l.id = v_liquidacion_id;
exception
  when unique_violation then
    raise exception 'Una o mas ordenes ya fueron liquidadas';
end;
$function$;

create or replace function public.liquidar_mecanico(
  p_mecanico_id uuid
)
returns table (
  liquidacion_id bigint,
  total_pagado numeric,
  cantidad_ordenes integer,
  fecha_pago date
)
language plpgsql
security invoker
set search_path = ''
as $function$
declare
  v_orden_ids bigint[];
begin
  if auth.uid() is null then
    raise exception 'No autenticado';
  end if;

  if private.current_user_role() is distinct from 'ADMIN' then
    raise exception 'Solo ADMIN puede registrar pagos';
  end if;

  select array_agg(o.id order by o.completed_at, o.id)
  into v_orden_ids
  from public.ordenes as o
  where o.mecanico_id = p_mecanico_id
    and o.estado = 'TERMINADA'
    and not exists (
      select 1
      from public.liquidacion_ordenes as lo
      where lo.orden_id = o.id
    );

  if coalesce(cardinality(v_orden_ids), 0) = 0 then
    raise exception 'Este mecanico no tiene pagos pendientes';
  end if;

  return query
  select
    resultado.liquidacion_id,
    resultado.total_pagado,
    resultado.cantidad_ordenes,
    resultado.fecha_pago
  from public.liquidar_ordenes_mecanico(
    p_mecanico_id,
    v_orden_ids
  ) as resultado;
end;
$function$;

